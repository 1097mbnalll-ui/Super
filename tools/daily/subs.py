def rx(words):
    out = []
    for w in words.split('|'):
        w = w.strip()
        if not w: continue
        whole = w.endswith('!'); w = w.rstrip('!').replace(' ', r'\s?')
        out.append(w + (r'(?=\s)' if whole else ''))
    return re.compile(r'(?<=\s)(?:و|ب|بال|ال|لل|وال|ل|فال)?(?:' + '|'.join(out) + ')')

