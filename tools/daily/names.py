import re
AD=str.maketrans('٠١٢٣٤٥٦٧٨٩٫','0123456789.')
L=r'(?![A-Za-z؀-ۿ])'   # نهاية الكلمة
SPELL={'شوكلاته':'شوكولاتة','شوكلاتة':'شوكولاتة','شكولاته':'شوكولاتة','شكولاتة':'شوكولاتة','شيكولاته':'شوكولاتة','شيكولاتة':'شوكولاتة','شوكولاته':'شوكولاتة','شوكولا':'شوكولاتة','شكلاته':'شوكولاتة',
 'بالشوكلاته':'بالشوكولاتة','بالشوكلاتة':'بالشوكولاتة','بالشكولاته':'بالشوكولاتة','بالشكولاتة':'بالشوكولاتة','بالشيكولاته':'بالشوكولاتة','بالشوكولاته':'بالشوكولاتة',
 'بسكوت':'بسكويت','نيفياء':'نيفيا','نيفاء':'نيفيا','نوفاء':'نوفا','ركسونا':'ريكسونا','فانيلا':'فانيليا','سايل':'سائل','حدايق':'حدائق','سيارت':'سيارات','ملي':'مل','ملل':'مل',
 'حبه':'حبة','علبه':'علبة','عبوه':'عبوة','قطعه':'قطعة','شوربه':'شوربة','حلاوه':'حلاوة','مطبوخه':'مطبوخة','مكرونه':'مكرونة','معكرونه':'معكرونة','جبنه':'جبنة','زبده':'زبدة','قهوه':'قهوة','كريمه':'كريمة',
 'نكهه':'نكهة','بنكهه':'بنكهة','بنكة':'بنكهة','فطيره':'فطيرة','عائليه':'عائلية','طبيعيه':'طبيعية','صغيره':'صغيرة','كبيره':'كبيرة','ملونه':'ملونة','مبلله':'مبللة','رضاعه':'رضاعة','حلمه':'حلمة','فرشه':'فرشة','فرشاه':'فرشاة',
 'مجففه':'مجففة','مقليه':'مقلية','مشكله':'مشكلة','منوعه':'منوعة','مثلجه':'مثلجة','معلبه':'معلبة','طازجه':'طازجة','مملحه':'مملحة','محمصه':'محمصة','ليفه':'ليفة','مرايه':'مراية','مغرفه':'مغرفة','طاسه':'طاسة','عروسه':'عروسة','لعبه':'لعبة','حاسبه':'حاسبة','دفايه':'دفاية','برايه':'براية','كمامه':'كمامة','مبخره':'مبخرة','مبشره':'مبشرة','زراديه':'زرادية','السنبله':'السنبلة','الوليمه':'الوليمة','الوفره':'الوفرة','وفره':'وفرة','كنانه':'كنانة','الريحه':'الريحة','ريحه':'ريحة','الدجاجه':'الدجاجة','بيضه':'بيضة'}
KEEP_H={'وجه','مياه','الله','شفاه','فواكه','كراميله','نكهه'}
def clean(name):
    s=str(name).translate(AD)
    s=s.replace('ـ','')
    s=re.sub(r'[ \t ]+',' ',s).strip()
    s=re.sub(r'\.{2,}|(?<![\d])\.(?![\d])',' ',s)           # نقاط زايدة (ما عدا 2.5)
    s=re.sub(r'(?<=\d)\s*[*xX×]\s*(?=\d)',' × ',s)           # 12*36 → 12 × 36
    s=re.sub(r'(?<=[؀-ۿ])\s*[*]\s*(?=\d)',' × ',s)
    s=re.sub(r'(?<!\d)0+(?=[1-9]\d*(?:\.\d+)?\s*(?:مل|جم|غ|ج|لتر))','',s)   # 0250مل → 250مل
    # الوحدات بعد الرقم
    s=re.sub(r'(\d+(?:\.\d+)?)\s*(?:كيلو\s*جرام|كيلوجرام|كيلو|كجم|كغ|كم|kg|KG|Kg)'+L,r'\1 كجم',s)
    s=re.sub(r'(\d+(?:\.\d+)?)\s*(?:جرام|غرام|جم|غم|غ|ج|gm|gr|g|G)'+L,r'\1 جم',s)
    s=re.sub(r'(\d+(?:\.\d+)?)\s*(?:ملي\s*لتر|مل|ملل|ملي|ml|ML|Ml)'+L,r'\1 مل',s)
    s=re.sub(r'(\d+(?:\.\d+)?)\s*(?:لتر|ليتر|لت|ltr|lt|L|l)'+L,r'\1 لتر',s)
    s=re.sub(r'(?<=[؀-ۿ])(?=\d)',' ',s)            # اكس150 → اكس 150
    s=re.sub(r'(?<=\d)(?=[؀-ۿ])',' ',s)            # 21رقم → 21 رقم
    out=[]
    for w in s.split(' '):
        if w in SPELL: w=SPELL[w]
        elif re.fullmatch(r'[؀-ۿ]{4,}يه',w) and w not in KEEP_H: w=w[:-1]+'ة'
        out.append(w)
    s=' '.join(out)
    s=re.sub(r'\s*/\s*',' / ',s); s=re.sub(r'\s+([,،)])',r'\1',s); s=re.sub(r'\(\s+','(',s)
    s=re.sub(r'\s+',' ',s).strip(' -_/.,،+')
    return s
if __name__=='__main__':
    import json,sys
    d=json.load(open(sys.argv[2] if len(sys.argv)>2 else 'data.json'))
    ch=[(p['name'],clean(p['name'])) for p in d['products'] if clean(p['name'])!=p['name']]
    print('changed',len(ch),'of',len(d['products']))
    import random; random.seed(int(sys.argv[1]) if len(sys.argv)>1 else 1)
    for a,b in random.sample(ch,70): print(a,' ⟶ ',b)
