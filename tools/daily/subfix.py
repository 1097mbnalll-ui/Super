def hit(n, words):
    for w in words.split('|'):
        w = nz(w).strip()
        if not w: continue
        if w.endswith('!'):
            if re.search(r'(^|\s)' + re.escape(w[:-1]) + r'(\s|$)', n): return True
        elif w in n: return True
    return False

def sub_of(cat, name):
    n = nz(name)
    for sid, words in RULES.get(cat, []):
        if not words: return sid
        for w in words.split('|'):
            w = nz(w).strip()
            if w.endswith('!'):
                if re.search(r'(^|\s)' + re.escape(w[:-1]) + r'(\s|$)', n): return sid
            elif w and w in n: return sid
    return None

def main():
    path = sys.argv[1]; apply = '--apply' in sys.argv; every = '--all' in sys.argv
    d = json.load(open(path)); cats = {c['id']: c for c in d['cats']}
    for cid, (nm, en) in CAT_NAMES.items():
        if cid in cats: cats[cid]['name'] = nm; cats[cid]['name_en'] = en
    for cid, subs in SUBS.items():
        if cid in cats: cats[cid]['subs'] = [{'id': i, 'name': n} for i, n in subs]
    moved, assigned = [], collections.Counter()
    for p in d['products']:
        n = nz(p['name'])
        valid0 = {x for x, _ in SUBS.get(p['cat'], [])}
        if not every and p.get('sub') in valid0 or (not every and p['cat'] not in SUBS): continue   # بدون --all: الجديد واللي بدون قسم فرعي بس
        for frm, words, to, ts in MOVES:
            if p['cat'] == frm and hit(n, words):
                moved.append((p['name'], frm, to)); p['cat'] = to
                if ts: p['sub'] = ts
                else: p.pop('sub', None)
                break
        for c, words, sb, no in FORCE:
            if p['cat'] == c and hit(n, words) and not (no and hit(n, no)):
                if p.get('sub') != sb: p['sub'] = sb; assigned[(c, sb)] += 1
                break
        else:
            pass
        if p['cat'] in RULES and not any(p['cat'] == c and hit(n, words) and not (no and hit(n, no)) for c, words, sb, no in FORCE):
            valid = {s for s, _ in SUBS.get(p['cat'], [])}
            if every and p['cat'] in ('tea',) or not p.get('sub') or p.get('sub') not in valid:
                s = sub_of(p['cat'], p['name'])
                if s and s != p.get('sub'): p['sub'] = s; assigned[(p['cat'], s)] += 1
    left = collections.Counter(p['cat'] for p in d['products'] if p['cat'] in SUBS and not p.get('sub'))
